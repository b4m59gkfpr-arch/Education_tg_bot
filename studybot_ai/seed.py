def get_questions_for_subject(subject_name: str) -> list[tuple]:
    """Подбирает подходящие вопросы в зависимости от названия предмета."""
    for key, questions in QUESTION_TEMPLATES.items():
        if key.lower() in subject_name.lower():
            return questions
    return DEFAULT_QUESTIONS


def subject_id_by_name(name: str, group_id: int) -> int:
    """Поиск ID предмета по его названию в рамках конкретной группы."""
    for subject in list_subjects(group_id):
        if subject["name"] == name:
            return subject["id"]
    raise RuntimeError(f"Subject not found: {name}")


def main() -> None:
    print("Инициализация базы данных...")
    init_db()

    # Фиксированный пароль для всех демо-преподавателей
    password_hash = generate_password_hash("Password123!")

    for t_data in TEACHERS_DATA:
        email = t_data["email"]
        full_name = t_data["full_name"]
        
        # 1. Проверка/создание преподавателя
        teacher = get_teacher_by_email(email)
        if not teacher:
            teacher_id = create_teacher(email, password_hash, full_name)
            print(f"Создан преподаватель: {full_name} ({email})")
        else:
            teacher_id = teacher["id"]
            print(f"Преподаватель {full_name} уже существует.")

        # 2. Создание групп преподавателя
        for g_data in t_data["groups"]:
            group_name = g_data["name"]
            
            # Проверяем, существует ли группа
            existing_groups = list_groups(teacher_id)
            group_id = next((g["id"] for g in existing_groups if g["name"] == group_name), None)
            
            if not group_id:
                group_id = create_group(group_name, teacher_id)
                print(f"  Создана группа: {group_name}")
            else:
                print(f"  Группа {group_name} уже существует.")

            # 3. Создание предметов для группы
            for s_name in g_data["subjects"]:
                existing_subjects = {s["name"] for s in list_subjects(group_id)}
                if s_name not in existing_subjects:
                    add_subject(s_name, group_id)
                    print(f"    Добавлен предмет: {s_name}")
                
                subject_id = subject_id_by_name(s_name, group_id)

                # 4. Добавление конспекта
                add_note(
                    subject_id,
                    f"Введение в {s_name}",
                    f"Конспект лекции по предмету {s_name}. Данный материал включает основные понятия, теоретические основы и практические примеры применения методов данной дисциплины."
                )

                # 5. Добавление вопросов и генерация лога AI-теста
                questions = get_questions_for_subject(s_name)
                json_questions = []
                
                for idx, q in enumerate(questions):
                    add_question(
                        subject_id,
                        q[0],  # вопрос
                        q[1],  # опция A
                        q[2],  # опция B
                        q[3],  # опция C
                        q[4],  # опция D
                        q[5]   # правильный ответ
                    )
                    
                    json_questions.append({
                        "question": q[0],
                        "option_a": q[1],
                        "option_b": q[2],
                        "option_c": q[3],
                        "option_d": q[4],
                        "correct_answer": q[5]
                    })
                
                # Запись в логи генераций тестов (чтобы страница "Прошлые тесты" не была пустой)
                save_generated_test(
                    subject_id,
                    f"Тест по разделу {s_name}",
                    f"Исходный материал лекции по теме {s_name}.",
                    f"Сгенерированный конспект по предмету {s_name}.",
                    json.dumps(json_questions, ensure_ascii=False)
                )

    print("\nЗаполнение демонстрационной базы данных успешно завершено!")


if __name__ == "__main__":
    main()
